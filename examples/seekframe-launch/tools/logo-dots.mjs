// Samples the Seekframe mark (a halftone eye in a film strip) into dots the film can animate.
// Usage: node examples/seekframe-launch/tools/logo-dots.mjs [cell=7]   -> examples/seekframe-launch/logo-dots.js
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { PNG } = require('pngjs');
const here = path.dirname(new URL(import.meta.url).pathname), root = path.resolve(here, '../../..');
const img = PNG.sync.read(fs.readFileSync(path.join(root, 'assets/brand/seekframe-mark.png')));
const cell = +(process.argv[2] || 7), cols = Math.floor(img.width / cell), rows = Math.floor(img.height / cell);
const ink = [], lime = [];
for (let r = 0; r < rows; r++) for (let c = 0; c < cols; c++) {
  let k = 0, g = 0, n = 0;
  for (let y = r * cell; y < (r + 1) * cell; y++) for (let x = c * cell; x < (c + 1) * cell; x++) {
    const i = (y * img.width + x) * 4, R = img.data[i], G = img.data[i + 1], B = img.data[i + 2], L = (.2126 * R + .7152 * G + .0722 * B) / 255;
    n++; if (L < .3) k++; else if (G > B + 40 && G > 120) g++;
  }
  // radius as a fraction of the cell (area-true); 0..9 so it fits one character
  const q = v => Math.min(9, Math.round(Math.sqrt(v / n) * 9 * .78));
  ink.push(q(k)); lime.push(q(g));
}
const out = `/* generated by tools/logo-dots.mjs from assets/brand/seekframe-mark.png: halftone dot radii per cell (0-9) */\nwindow.SEEKFRAME_DOTS = ${JSON.stringify({ cols, rows, ink: ink.join(''), lime: lime.join('') })};\n`;
fs.writeFileSync(path.join(here, '../logo-dots.js'), out);
console.log(`${cols}x${rows} cells, ${(out.length / 1024).toFixed(1)} KB`);
