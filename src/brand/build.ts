// brand.json -> brand.css (fonts + CSS variables) and brand.js (window.BRAND). Output goes next to brand.json.
import fs from 'node:fs';
import path from 'node:path';
import { ASSETS_DIR } from '../core/workspace';
import type { BrandFont } from '../types';



const FALLBACK = [   // bundled OFL fonts (assets/fonts), used when a brand font is missing or has no glyphs for a script
  { family: 'SF Inter', file: 'inter-latin-{w}-normal.woff2', weights: [400, 500, 600, 700, 800], range: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD' },
  { family: 'SF Plex Arabic', file: 'ibm-plex-sans-arabic-arabic-{w}-normal.woff2', weights: [400, 500, 600, 700], range: 'U+0600-06FF,U+0750-077F,U+0870-088E,U+0890-0891,U+0898-08E1,U+08E3-08FF,U+200C-200E,U+2010-2011,U+204F,U+2E41,U+FB50-FDFF,U+FE70-FE74,U+FE76-FEFC' },
];
const q = s => `'${String(s).replace(/'/g, "\\'")}'`;

function build(dir) {
  dir = path.resolve(dir || 'brand');
  const jf = path.join(dir, 'brand.json'); if (!fs.existsSync(jf)) throw new Error(`no brand.json in ${dir} (run: seekframe brand init)`);
  const B = JSON.parse(fs.readFileSync(jf, 'utf8'));
  const fontsDir = path.relative(dir, path.join(ASSETS_DIR, 'fonts')).split(path.sep).join('/');
  let css = `/* generated by \`seekframe brand build\` from brand.json — do not edit */\n`;
  const own: BrandFont[] = [];
  for (const f of B.fonts || []) {
    for (const [w, file] of Object.entries<string>(f.files || {})) {
      if (!fs.existsSync(path.join(dir, file))) continue;           // licensed fonts that are not in the repo are skipped; the fallback stack takes over
      css += `@font-face{font-family:${q(f.family)};src:url(${file});font-weight:${w};font-display:block}\n`;
    }
    own.push(f);
  }
  for (const f of FALLBACK) for (const w of f.weights) css += `@font-face{font-family:${q(f.family)};src:url(${fontsDir}/${f.file.replace('{w}', String(w))}) format('woff2');font-weight:${w};unicode-range:${f.range};font-display:block}\n`;
  const stack = role => [...own.filter(f => !f.role || f.role === role || f.role === 'both').map(f => q(f.family)), q('SF Inter'), q('SF Plex Arabic'), q('Apple Color Emoji'), q('Segoe UI Emoji'), q('Noto Color Emoji'), 'system-ui', 'sans-serif'].join(',');
  css += `:root{\n`;
  for (const [k, v] of Object.entries(B.colors || {})) css += `  --brand-${k}:${v};\n`;
  css += `  --font-display:${stack('display')};\n  --font-text:${stack('text')};\n}\n`;
  fs.writeFileSync(path.join(dir, 'brand.css'), css);
  fs.writeFileSync(path.join(dir, 'brand.js'), `/* generated by \`seekframe brand build\` */\nwindow.BRAND = ${JSON.stringify({ name: B.name, nameLocal: B.nameLocal, colors: B.colors, voice: B.voice, logo: B.logo }, null, 2)};\n`);
  return { dir, fonts: own.map(f => f.family), colors: Object.keys(B.colors || {}) };
}
export { build };
